/**
 * Distinctness check and report (catalogue task, Part D).
 *
 *   npx tsx scripts/distinctness.tsx [--png] [--with id,id]
 *
 * Prints the nearest pairs of designs by structure (colour and font left out), writes
 * docs/catalogue/distinctness-report.md, and with --png a side-by-side sheet of the closest pairs
 * (docs/catalogue/distinctness-pairs.png). Exit code 1 when two live designs are closer than the
 * threshold and the owner has not accepted the pair.
 */
import fs from 'node:fs';
import path from 'node:path';
import puppeteer from 'puppeteer-core';
import { DEFAULT_CONFIG } from '../src/modules/billing/config';
import accepted from '../src/modules/design/distinctness-accepted.json';
import { DESIGN_META } from '../src/modules/design/designs';
import {
  SIGNATURE_PARTS,
  THRESHOLD,
  nearestPairs,
  pairKey,
  type SignaturePart,
} from '../src/modules/design/distinctness';
import { DESIGN_IDS } from '../src/modules/resume/ids';
import type { DesignId } from '../src/modules/resume/schema';

const PART_LABEL: Record<SignaturePart, string> = {
  layout: 'layout',
  header: 'header',
  headings: 'heading style',
  entries: 'entry layout',
  decoration: 'decoration',
  placement: 'section placement',
  photo: 'photo',
  sideFill: 'side fill',
  container: 'section boxes / key numbers',
  skills: 'skills look',
  headingCase: 'heading case',
};
const SHOW = 15;

async function main() {
  const png = process.argv.includes('--png');
  // --with a,b: also check these designs (e.g. a new draft from the authoring kit).
  const withIdx = process.argv.indexOf('--with');
  const extra = withIdx > 0 ? (process.argv[withIdx + 1] ?? '').split(',').filter(Boolean) : [];
  const live = DESIGN_IDS.filter(
    (id) => DEFAULT_CONFIG.designs.find((d) => d.id === id)?.enabled || extra.includes(id),
  ) as DesignId[];
  const ok = new Map(accepted.map((p) => [pairKey(p.a, p.b), p.reason] as const));
  const pairs = nearestPairs(live);
  const failing = pairs.filter((p) => p.distance < THRESHOLD && !ok.has(pairKey(p.a, p.b)));
  const differs = (same: SignaturePart[]) =>
    (Object.keys(SIGNATURE_PARTS) as SignaturePart[])
      .filter((k) => !same.includes(k))
      .map((k) => PART_LABEL[k])
      .join(', ');
  const name = (id: DesignId) => DESIGN_META[id].name;

  const lines = [
    '# Design distinctness report',
    '',
    `Generated by \`npm run catalogue:distinct\`. ${live.length} live designs, ${pairs.length} pairs. Threshold ${THRESHOLD} (share of structure that differs; colour and font excluded).`,
    '',
    `| # | Pair | Distance | What differs | Status |`,
    `|---|---|---|---|---|`,
    ...pairs
      .slice(0, SHOW)
      .map(
        (p, i) =>
          `| ${i + 1} | ${name(p.a)} – ${name(p.b)} | ${p.distance.toFixed(2)} | ${differs(p.same)} | ${
            p.distance < THRESHOLD
              ? ok.has(pairKey(p.a, p.b))
                ? 'below threshold, accepted by owner'
                : '**below threshold — fails**'
              : 'ok'
          } |`,
      ),
    '',
    '## Side by side',
    '',
    ...pairs
      .slice(0, 8)
      .flatMap((p) => [
        `**${name(p.a)} – ${name(p.b)}** (${p.distance.toFixed(2)})`,
        '',
        `<img src="../../public/templates/${p.a}.webp" width="180"> <img src="../../public/templates/${p.b}.webp" width="180">`,
        '',
      ]),
  ];
  if (!extra.length) {
    fs.mkdirSync('docs/catalogue', { recursive: true });
    fs.writeFileSync('docs/catalogue/distinctness-report.md', lines.join('\n') + '\n');
  }

  const shown = extra.length
    ? pairs.filter((p) => extra.includes(p.a) || extra.includes(p.b)).slice(0, 5)
    : pairs.slice(0, SHOW);
  if (extra.length) console.log(`Nearest designs to ${extra.join(', ')}:`);
  for (const p of shown)
    console.log(
      `${p.distance.toFixed(3)}  ${name(p.a).padEnd(12)} ${name(p.b).padEnd(12)} differs: ${differs(p.same)}`,
    );

  if (png) {
    const img = (id: string) =>
      `data:image/webp;base64,${fs.readFileSync(path.join('public/templates', `${id}.webp`)).toString('base64')}`;
    const rows = pairs
      .slice(0, 8)
      .map(
        (p) => `<div class="row"><img src="${img(p.a)}"><img src="${img(p.b)}">
        <div class="t"><b>${name(p.a)} – ${name(p.b)}</b><br>distance ${p.distance.toFixed(2)}<br><small>differs: ${differs(p.same)}</small></div></div>`,
      )
      .join('');
    const browser = await puppeteer.launch({
      executablePath: process.env.CHROME_EXECUTABLE_PATH ?? '/usr/bin/google-chrome',
      args: ['--no-sandbox'],
    });
    const page = await browser.newPage();
    await page.setViewport({ width: 1100, height: 800, deviceScaleFactor: 1 });
    await page.setContent(
      `<style>body{font:14px system-ui;margin:16px;display:grid;grid-template-columns:1fr 1fr;gap:14px}
      .row{display:flex;gap:8px;align-items:flex-start;border:1px solid #ddd;border-radius:8px;padding:8px}
      img{width:150px;border:1px solid #ccc}.t{font-size:13px;line-height:1.4}</style>${rows}`,
    );
    await page.screenshot({ path: 'docs/catalogue/distinctness-pairs.png', fullPage: true });
    await browser.close();
  }

  if (failing.length) {
    console.error(
      `\n${failing.length} pair(s) of live designs are too close (below ${THRESHOLD}):\n` +
        failing.map((p) => `  ${p.a} – ${p.b} ${p.distance}`).join('\n') +
        '\nMake them differ in structure, or record the owner’s decision in src/modules/design/distinctness-accepted.json.',
    );
    process.exit(1);
  }
  console.log(`\nPASS: no unaccepted pair below ${THRESHOLD}.`);
}

void main();
